-- Statement drafts: one persisted draft body per (user, school).
-- Safe to re-run (IF NOT EXISTS). Spring connects as postgres (bypasses RLS);
-- public Data API has no policies.

CREATE TABLE IF NOT EXISTS public.statement_drafts (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
    school_id  bigint NOT NULL REFERENCES public.schools (id) ON DELETE CASCADE,
    body       text NOT NULL,
    updated_at timestamp NOT NULL DEFAULT now(),
    CONSTRAINT statement_drafts_user_school_uk UNIQUE (user_id, school_id)
);

CREATE INDEX IF NOT EXISTS statement_drafts_user_id_idx ON public.statement_drafts (user_id);
CREATE INDEX IF NOT EXISTS statement_drafts_school_id_idx ON public.statement_drafts (school_id);

ALTER TABLE public.statement_drafts ENABLE ROW LEVEL SECURITY;
