CREATE TABLE IF NOT EXISTS public.program_terms (
    id                      bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    school_id               bigint NOT NULL REFERENCES public.schools (id) ON DELETE CASCADE,
    term                    varchar(10) NOT NULL CHECK (term IN ('FALL', 'SPRING', 'SUMMER', 'WINTER')),
    start_year              integer NOT NULL,
    app_open_date           date,
    domestic_deadline       date,
    international_deadline  date,
    docs_deadline           date,
    accepting               boolean,
    source_url              text,
    last_verified           date,
    UNIQUE (school_id, term, start_year)
);

CREATE INDEX IF NOT EXISTS program_terms_school_id_idx ON public.program_terms (school_id);

ALTER TABLE public.program_terms ENABLE ROW LEVEL SECURITY;
